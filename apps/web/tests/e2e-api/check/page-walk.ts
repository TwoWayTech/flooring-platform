/**
 * What the whole-product check's browser walks share (the demo-script walk DS and the page-gate
 * matrix PGM, plan section 5.4, ADR 0058): what the generated coverage list and page gates say about
 * a page, which catalog route an `/api-proxy` answer reached, a log of a page's answers and writes,
 * the JSON a page was given, and how a page ended up (open, refused, switched off, failed to load).
 */

/** One screen as the coverage scan wrote it (page-coverage.json): how it reads its data in api mode. */
export interface CoveredScreen {
  file: string;
  /** "api", "mixed" (API and DemoStore), "demo-only" or "no data". */
  classification: string;
  hiddenInApiMode: boolean;
  /** The layouts around it, by name in `layouts`. */
  layouts: string[];
  /** ApiClient calls served by the API in api mode. */
  onApi: string[];
  /** ApiClient calls still answered by DemoStore in api mode (gap G5 when the page is mixed). */
  onDemo: string[];
  /** The catalog routes its API calls reach. */
  routes: string[];
}

/** page-coverage.json, generated by tests/unit/coverage-list.test.ts. */
interface PageCoverage {
  pages: Record<string, CoveredScreen>;
  layouts: Record<string, CoveredScreen>;
}

const COVERAGE_FILE = "apps/web/tests/e2e-api/check/page-coverage.json";
const GATES_FILE = "apps/web/tests/e2e-api/check/page-gates.json";

let coverage: PageCoverage | null = null;

/** The generated coverage of every page and layout, read once. */
function pageCoverage(): PageCoverage {
  coverage ??= JSON.parse(readRepoFile(COVERAGE_FILE)) as PageCoverage;
  return coverage;
}

/** The page a browser address opens, as the scan names pages: the path without its `?view=`. */
export function pageOf(href: string): string {
  return href.split("?")[0] ?? href;
}

/**
 * The scan's name for the page an address opens: the page itself, or the page with a `*` segment
 * that stands for a record (`/contracts/<id>` → `/contracts/*`). Throws when the scan has no such page.
 */
export function scanPage(href: string): string {
  const path = pageOf(href);
  const pages = Object.keys(pageCoverage().pages);
  const parts = path.split("/");
  const record = (page: string) => {
    const want = page.split("/");
    return want.length === parts.length && want.every((part, index) => part === "*" || part === parts[index]);
  };
  const found = pages.includes(path) ? path : pages.find(record);
  if (!found) throw new Error(`${COVERAGE_FILE} has no page for ${path}; regenerate it.`);
  return found;
}

/** The scan's entry for the page an address opens (`scanPage`). */
export function coveredPage(href: string): CoveredScreen {
  const entry = pageCoverage().pages[scanPage(href)];
  if (!entry) throw new Error(`${COVERAGE_FILE} has no page ${scanPage(href)}; regenerate it.`);
  return entry;
}

/** Every catalog route a page and the layouts around it reach, by the scan. */
export function staticRoutes(href: string): Set<string> {
  const page = coveredPage(href);
  const layouts = page.layouts.map((name) => pageCoverage().layouts[name]?.routes ?? []);
  return new Set([...page.routes, ...layouts.flat()]);
}

/**
 * The pages a product's role may open in api mode (page-gates.json, PG-3), each with the roles it
 * opens for. Pages with a `*` segment stand for a record and need one, so the matrix leaves them out.
 */
export function gatedPages(product: ProductKey): Map<string, string[]> {
  const gates = JSON.parse(readRepoFile(GATES_FILE)) as Record<ProductKey, Record<string, string[]>>;
  return new Map(Object.entries(gates[product]).filter(([page]) => !page.includes("*")));
}

/** A catalog route split into its path segments, parameters as `:p`. */
interface CatalogEntry {
  name: string;
  verb: string;
  parts: string[];
}

let catalog: CatalogEntry[] | null = null;

/** The API's route catalog (route-requirements.json), read once. */
function routeCatalog(): CatalogEntry[] {
  catalog ??= [...routeRequirements().keys()].map((name) => {
    const [verb = "", path = ""] = name.split(" ");
    return { name, verb, parts: normalPath(path).split("/") };
  });
  return catalog;
}

/** How many parameters a catalog route has: a literal segment wins over a parameter. */
function parameterCount(entry: CatalogEntry): number {
  return entry.parts.filter((part) => part === ":p").length;
}

/**
 * The catalog route (`GET /invoices/:id`) a request reached, from its method and its path after
 * `/api-proxy`, or null for a path the catalog doesn't have. A literal segment beats a parameter, so
 * `/quotes/new` would match `GET /quotes/new` before `GET /quotes/:id`.
 */
export function catalogRoute(method: string, path: string): string | null {
  const parts = normalPath(path).split("/");
  const fits = routeCatalog().filter(
    (entry) =>
      entry.verb === method &&
      entry.parts.length === parts.length &&
      entry.parts.every((part, index) => part === ":p" || part === parts[index]),
  );
  fits.sort((a, b) => parameterCount(a) - parameterCount(b));
  return fits[0]?.name ?? null;
}

/** Whether the route matrix lets a product's default role past the guards on a route (route-role-matrix.txt). */
export function matrixAllows(route: string, product: ProductKey, role: string): boolean | null {
  return routeRoles().get(route)?.[product].has(role) ?? null;
}

/** One answer a screen got through the web's proxy. */
export interface ProxyAnswer {
  method: string;
  /** The path after `/api-proxy`, without the query. */
  path: string;
  status: number;
  /** The catalog route it reached, or null. */
  route: string | null;
}

/** What a page sent through `/api-proxy` while it was watched. */
export interface ProxyLog {
  answers: ProxyAnswer[];
  /** Every write (any method but GET) the page sent, as its catalog route or its raw path. */
  writes: string[];
  /** Forgets everything seen so far, before the next page. */
  clear(): void;
}

const PROXY = "/api-proxy";

/** The method and the path after `/api-proxy` of a request, or null when it isn't the proxy's. */
function proxied(request: Request): { method: string; path: string } | null {
  const { pathname } = new URL(request.url());
  if (!pathname.startsWith(`${PROXY}/`)) return null;
  return { method: request.method(), path: pathname.slice(PROXY.length) };
}

/** Watches a page's `/api-proxy` traffic from now on: every answer with its status, and every write. */
export function watchProxy(page: Page): ProxyLog {
  const log: ProxyLog = {
    answers: [],
    writes: [],
    clear() {
      log.answers.length = 0;
      log.writes.length = 0;
    },
  };
  page.on("request", (request: Request) => {
    const call = proxied(request);
    if (call && call.method !== "GET" && call.method !== "HEAD")
      log.writes.push(catalogRoute(call.method, call.path) ?? `${call.method} ${call.path}`);
  });
  page.on("response", (response: Response) => {
    const call = proxied(response.request());
    if (call) log.answers.push({ ...call, status: response.status(), route: catalogRoute(call.method, call.path) });
  });
  return log;
}

/** One JSON answer a page was given through `/api-proxy`, by the catalog route it reached. */
export interface ProxyBody {
  route: string;
  body: unknown;
}

/**
 * Keeps every successful JSON answer a page gets through `/api-proxy` from now on; `read` waits for
 * the bodies still arriving. An answer whose body is gone because the page moved on is left out.
 */
export function watchBodies(page: Page): { read(): Promise<ProxyBody[]> } {
  const pending: Promise<ProxyBody | null>[] = [];
  page.on("response", (response: Response) => {
    const call = proxied(response.request());
    if (!call || !response.ok() || !(response.headers()["content-type"] ?? "").includes("json")) return;
    const route = catalogRoute(call.method, call.path) ?? `${call.method} ${call.path}`;
    pending.push(
      response.json().then(
        (body: unknown) => ({ route, body }),
        () => null,
      ),
    );
  });
  return {
    async read() {
      return (await Promise.all(pending)).filter((answer): answer is ProxyBody => answer !== null);
    },
  };
}

/** How a page ended up once its reads had settled. */
export type PageState = "open" | "refused" | "switched off" | "could not load" | "signed out" | "still loading";

/** The words `NoAccess` shows on a page the viewer may not open (components/no-access.tsx). */
export const NO_ACCESS = "You don't have access to this page.";
/** The words `PageGate` shows on a page whose feature is switched off (components/page-gate.tsx). */
export const SWITCHED_OFF = "This feature is switched off in this demo.";
/** The words `QueryFallback` shows when a screen's read failed (components/query-fallback.tsx). */
export const COULD_NOT_LOAD = "This page could not load its data.";

/** How long a page may take to drop its last skeleton after the network went quiet. */
const SKELETON_TIMEOUT = 10_000;

/**
 * Waits until the page's reads have settled: the network has been quiet for half a second and no
 * skeleton is left. Returns how the page ended up.
 */
export async function settle(page: Page): Promise<PageState> {
  await page.waitForLoadState("networkidle");
  if (new URL(page.url()).pathname === "/login") return "signed out";
  try {
    await expect(page.locator('[data-slot="skeleton"]')).toHaveCount(0, { timeout: SKELETON_TIMEOUT });
  } catch {
    return "still loading";
  }
  return pageState(page);
}

/** Opens an address and waits until its reads have settled (`settle`). */
export async function openAndSettle(page: Page, href: string): Promise<PageState> {
  await page.goto(href);
  return settle(page);
}

/** The address the page is on, as page-gates.json writes pages: the path, plus `?view=` when there is one. */
export function addressOf(page: Page): string {
  const url = new URL(page.url());
  const view = url.searchParams.get("view");
  return view ? `${url.pathname}?view=${view}` : url.pathname;
}

/** What each failed read says under "This page could not load its data." (QueryFallback). */
export async function loadFailures(page: Page): Promise<string[]> {
  const boxes = page.getByRole("alert").filter({ hasText: COULD_NOT_LOAD });
  return (await boxes.allInnerTexts()).map((text) => text.replace(COULD_NOT_LOAD, "").replace("Try again", "").trim());
}

/** How the page on screen stands now: refused, switched off, failed to load, or open. */
export async function pageState(page: Page): Promise<PageState> {
  if (await page.getByText(NO_ACCESS, { exact: true }).isVisible()) return "refused";
  if (await page.getByText(SWITCHED_OFF, { exact: true }).isVisible()) return "switched off";
  if ((await page.getByText(COULD_NOT_LOAD, { exact: true }).count()) > 0) return "could not load";
  return "open";
}

/** The error toasts on screen (sonner), by their text: an API error no screen handled shows as one. */
export async function errorToasts(page: Page): Promise<string[]> {
  return page.locator('[data-sonner-toast][data-type="error"]').allInnerTexts();
}

/**
 * Signs a seeded person in afresh: their MFA, passkeys, sessions and the per-IP sign-in limit are
 * reset first (SH-18), so the walk never waits out the limit and an MFA role enrols again. The
 * reset runs on the throwaway server `assertThrowawayDb` checked.
 */
export async function signInFresh(
  personas: PersonaPool,
  server: FreshTestServer,
  email: string,
  role: DefaultRoleKey,
): Promise<Persona> {
  await resetAuthState(server.controlUrl, [email]);
  return personas.open(email, { mfa: rolesRequireMfa([role]) });
}

/**
 * Notes how a page reads its data in api mode, from page-coverage.json (MF-7): a mixed page is gap
 * G5 and names what it still reads from DemoStore. One note per page and test.
 */
export function noteCoverage(href: string): void {
  const page = coveredPage(href);
  const mixed = page.classification === "mixed";
  const type = mixed ? "GAP-G5, mixed page" : `page ${page.classification}`;
  const description = `${scanPage(href)}${mixed ? `: still reads ${page.onDemo.join(", ")} from DemoStore` : ""}`;
  const { annotations } = test.info();
  if (!annotations.some((note) => note.type === type && note.description === description))
    annotations.push({ type, description });
}

/**
 * Opens a screen as a persona and waits for the screen's own read (`GET` on `read`) to answer 200,
 * then for its other reads to settle; the screen must be open, with no failed read and no error
 * toast. Notes the page's coverage and returns the read's JSON.
 */
export async function openScreen<T>(
  persona: Persona,
  href: string,
  read: RegExp,
  query: Readonly<Record<string, string>> = {},
): Promise<T> {
  const answer = waitForAnswer<T>(persona.page, "GET", read, query);
  await persona.page.goto(href);
  const body = await answer;
  expect(await settle(persona.page), `${href} as ${persona.email}`).toBe("open");
  expect(await errorToasts(persona.page), `error toasts on ${href}`).toEqual([]);
  noteCoverage(href);
  return body;
}
