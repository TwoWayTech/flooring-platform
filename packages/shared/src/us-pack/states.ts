/** Two-letter USPS code of a state or DC. */
export type StateCode = (typeof US_STATES)[number][0];

/** Full name for a state code. */
export function stateName(code: string): string {
  return US_STATES.find(([c]) => c === code)?.[1] ?? code;
}

/** Whether a string is a valid state code. */
export function isStateCode(code: string): code is StateCode {
  return US_STATES.some(([c]) => c === code);
}

